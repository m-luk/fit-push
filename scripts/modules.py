#!/usr/bin/env python3
"""Module tooling: scaffold, check and document fit-git modules.

    python scripts/modules.py new <id> --owner <github-id> --name "Nice name" [--provides page,api]
    python scripts/modules.py check [<id> ...]      # all modules when no id is given
    python scripts/modules.py docs                  # regenerate modules/INDEX.md and docs/MODULES_MANUAL.md
    python scripts/modules.py list

Rules are in modules/RULES.md; ``check`` enforces the machine-checkable ones and is
run by the test suite (tests/test_module_contract.py) and CI.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.modules import DEFAULT_DIR, ID_RE, discover, validate_manifest  # noqa: E402
from app.sdk import SDK_VERSION  # noqa: E402

INDEX = DEFAULT_DIR / "INDEX.md"
COMBINED_MANUAL = ROOT / "docs" / "MODULES_MANUAL.md"
README_SECTIONS = {"Intent": 20, "How it works": 15, "Data": 5}  # heading -> minimum words
MANUAL_SECTIONS = {"What it does": 10, "How to use": 10, "Limitations": 3}
MAX_CODE_LINES = 600  # backend.py + frontend.js; bigger modules should be split
ALLOWED_THIRD_PARTY = {"fastapi", "pydantic", "numpy", "starlette"}
PLACEHOLDER = re.compile(r"\bTODO\b|<fill in|lorem ipsum", re.IGNORECASE)
EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")
GENERATED = "<!-- generated by scripts/modules.py docs; do not edit -->"


# ----------------------------------------------------------------------------- check
def _sections(md: str) -> dict[str, str]:
    """'## Heading' -> body text."""
    out, cur = {}, None
    for line in md.splitlines():
        m = re.match(r"^##\s+(.+?)\s*$", line)
        if m:
            cur = m.group(1).strip()
            out[cur] = ""
        elif cur:
            out[cur] += line + "\n"
    return out


def _check_doc(path: Path, required: dict[str, int]) -> list[str]:
    if not path.is_file():
        return [f"{path.name} is missing"]
    text = path.read_text(encoding="utf-8")
    errs = []
    if PLACEHOLDER.search(text):
        errs.append(f"{path.name} still contains placeholders (TODO / <fill in ...>)")
    if not text.lstrip().startswith("# "):
        errs.append(f"{path.name} must start with a '# Title' line")
    secs = _sections(text)
    for name, min_words in required.items():
        words = len(secs.get(name, "").split())
        if name not in secs:
            errs.append(f"{path.name} needs a '## {name}' section")
        elif words < min_words:
            errs.append(f"{path.name}: '## {name}' is too short ({words} words, need {min_words}+)")
    if EMAIL.search(text):
        errs.append(f"{path.name} contains an e-mail address; use GitHub ids only")
    return errs


def _check_backend(path: Path, module_id: str) -> list[str]:
    errs = []
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError as exc:
        return [f"backend.py does not parse: {exc}"]
    stdlib = set(sys.stdlib_module_names)
    for node in ast.walk(tree):
        names: list[str] = []
        if isinstance(node, ast.Import):
            names = [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                errs.append("backend.py: relative imports are not allowed (modules are single files)")
                continue
            names = [node.module or ""]
        for name in names:
            top = name.split(".")[0]
            if top == "app" and name != "app.sdk":
                errs.append(f"backend.py imports {name}: only 'app.sdk' may be used from the core")
            elif top not in stdlib and top not in ALLOWED_THIRD_PARTY and top != "app":
                errs.append(f"backend.py imports {name}: not in requirements (allowed: {sorted(ALLOWED_THIRD_PARTY)})")
    if not any(isinstance(n, ast.FunctionDef) and n.name == "register" for n in tree.body):
        errs.append("backend.py must define register(ctx)")
    src = path.read_text(encoding="utf-8")
    for m in re.finditer(r"CREATE\s+(?:UNIQUE\s+)?(?:TABLE|INDEX)\s+(?:IF\s+NOT\s+EXISTS\s+)?[\"`]?(\w+)", src, re.I):
        if not m.group(1).startswith(f"m_{module_id}_") and "table(" not in src[max(0, m.start() - 80) : m.end() + 40]:
            errs.append(f"backend.py creates {m.group(1)}: use ctx.db.table(...) (tables must be m_{module_id}_*)")
    return errs


def _check_frontend(path: Path, module_id: str) -> list[str]:
    src = path.read_text(encoding="utf-8")
    errs = []
    if "window.fitgit" not in src or not re.search(r"\.register(Page|ActivityCard)\(", src):
        errs.append("frontend.js must use window.fitgit and register via registerPage / registerActivityCard")
    if not re.search(rf"module:\s*[\"']{module_id}[\"']", src):
        errs.append(f'frontend.js registrations must declare module: "{module_id}"')
    for pat, why in [
        (r"\b(prompt|alert)\s*\(", "prompt()/alert() are blocked in embedded browsers; use fitgit.askName/toast"),
        (
            r"getElementById\(\s*[\"']main[\"']\)|querySelector\(\s*[\"']#main",
            "do not touch #main; render into the element you are given",
        ),
        (r"window\.fitgit\s*=", "do not replace window.fitgit"),
        (
            r"localStorage\.(get|set)Item\(\s*[\"'](?!fitgit:m:" + module_id + ")",
            f"localStorage keys must start with 'fitgit:m:{module_id}'",
        ),
    ]:
        if re.search(pat, src):
            errs.append(f"frontend.js: {why}")
    if not src.lstrip().startswith(("//", "/*", '"use strict"', "'use strict'", "(")):
        errs.append("frontend.js should start with a comment saying what it registers")
    return errs


def check_module(info) -> tuple[list[str], list[str]]:
    """(errors, warnings) for one module."""
    folder, errs, warns = info.dir, [], []
    if info.status == "error" and not info.manifest:
        return info.errors, warns
    errs += validate_manifest(info.manifest, folder)
    if EMAIL.search(json.dumps(info.manifest)):
        errs.append("module.json contains an e-mail address; use GitHub ids only")
    errs += _check_doc(folder / "README.md", README_SECTIONS)
    errs += _check_doc(folder / "MANUAL.md", MANUAL_SECTIONS)
    if (folder / "backend.py").is_file():
        errs += _check_backend(folder / "backend.py", info.id)
    if (folder / "frontend.js").is_file():
        errs += _check_frontend(folder / "frontend.js", info.id)
    test_file = folder / "tests" / f"test_{info.id}.py"
    if not test_file.is_file():
        errs.append(f"tests/test_{info.id}.py is missing")
    elif not re.search(r"^def test_", test_file.read_text(encoding="utf-8"), re.M):
        errs.append(f"tests/test_{info.id}.py has no test functions")
    code_lines = sum(
        len((folder / f).read_text(encoding="utf-8").splitlines())
        for f in ("backend.py", "frontend.js")
        if (folder / f).is_file()
    )
    if code_lines > MAX_CODE_LINES:
        warns.append(f"{code_lines} lines of code (> {MAX_CODE_LINES}): consider splitting into smaller modules")
    unexpected = {p.name for p in folder.iterdir()} - {
        "module.json",
        "README.md",
        "MANUAL.md",
        "backend.py",
        "frontend.js",
        "frontend.css",
        "tests",
        "__pycache__",
    }
    if unexpected:
        errs.append(f"unexpected files: {', '.join(sorted(unexpected))} (keep modules to the standard layout)")
    return errs, warns


def cmd_check(ids: list[str]) -> int:
    infos = [i for i in discover() if not ids or i.id in ids]
    if ids and len(infos) != len(ids):
        print("unknown module(s):", ", ".join(set(ids) - {i.id for i in infos}))
        return 2
    failed = 0
    for info in infos:
        errs, warns = check_module(info)
        print(f"{'FAIL' if errs else 'ok  '} {info.id}")
        for e in errs:
            print(f"     ✗ {e}")
        for w in warns:
            print(f"     ! {w}")
        failed += bool(errs)
    stale = docs_outdated()
    if stale:
        print(f"FAIL generated docs are out of date: {', '.join(stale)} -> run: python scripts/modules.py docs")
    if not infos:
        print("no modules found")
    return 1 if failed or stale else 0


# ----------------------------------------------------------------------------- docs
def render_index() -> str:
    rows = []
    for i in discover():
        m = i.manifest
        owner = m.get("owner", {}).get("github", "?")
        rows.append(
            f"| [{i.id}]({i.id}/README.md) | {m.get('name', '?')} | {m.get('version', '?')} | "
            f"[@{owner}](https://github.com/{owner}) | {m.get('summary', '')} | "
            f"{', '.join(m.get('provides', []))} | [manual]({i.id}/MANUAL.md) |"
        )
    return "\n".join(
        [
            GENERATED,
            "# Module registry",
            "",
            f"Modules installed in this repository (SDK {SDK_VERSION}). Each row comes from the module's",
            "`module.json`; regenerate with `python scripts/modules.py docs`. Rules: [RULES.md](RULES.md).",
            "",
            "| Id | Name | Version | Owner | Summary | Provides | Manual |",
            "|---|---|---|---|---|---|---|",
            *rows,
            "",
        ]
    )


def render_manual() -> str:
    parts = [
        GENERATED,
        "# fit-git module manuals",
        "",
        "User manuals of all installed modules, collected from `modules/<id>/MANUAL.md`.",
        "",
    ]
    for i in discover():
        path = i.dir / "MANUAL.md"
        if not path.is_file():
            continue
        body = path.read_text(encoding="utf-8").strip().splitlines()
        title = body[0].lstrip("# ").strip() if body else i.id
        owner = i.manifest.get("owner", {}).get("github", "?")
        parts += [f"## {title}", "", f"*Module `{i.id}` v{i.manifest.get('version', '?')} · owner @{owner}*", ""]
        parts += ["#" + line if line.startswith("#") else line for line in body[1:]]  # demote headings
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def docs_outdated() -> list[str]:
    stale = []
    for path, content in ((INDEX, render_index()), (COMBINED_MANUAL, render_manual())):
        if not path.is_file() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != content:
            stale.append(str(path.relative_to(ROOT)))
    return stale


def cmd_docs() -> int:
    COMBINED_MANUAL.parent.mkdir(exist_ok=True)
    INDEX.write_text(render_index(), encoding="utf-8", newline="\n")
    COMBINED_MANUAL.write_text(render_manual(), encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(ROOT)} and {COMBINED_MANUAL.relative_to(ROOT)}")
    return 0


# ----------------------------------------------------------------------------- new
def cmd_new(module_id: str, owner: str, name: str, provides: list[str]) -> int:
    if not ID_RE.match(module_id):
        print("id must match [a-z][a-z0-9_]{1,31}")
        return 2
    folder = DEFAULT_DIR / module_id
    if folder.exists():
        print(f"{folder} already exists")
        return 2
    templates = ROOT / "modules" / "_template"
    (folder / "tests").mkdir(parents=True)
    subst = {
        "__ID__": module_id,
        "__NAME__": name,
        "__OWNER__": owner,
        "__PROVIDES__": json.dumps(provides),
        "__SDK__": SDK_VERSION.split(".")[0],
    }
    for src in templates.rglob("*"):
        if src.is_dir():
            continue
        rel = src.relative_to(templates).as_posix().replace("__ID__", module_id).removesuffix(".tmpl")
        text = src.read_text(encoding="utf-8")
        for k, v in subst.items():
            text = text.replace(k, v)
        (folder / rel).parent.mkdir(parents=True, exist_ok=True)
        (folder / rel).write_text(text, encoding="utf-8", newline="\n")
    if "page" not in provides and "activity-card" not in provides:
        (folder / "frontend.js").unlink()
    if "api" not in provides and "events" not in provides:
        (folder / "backend.py").unlink()
    print(f"created {folder}. Next: fill README.md (intent) FIRST, then code, tests and MANUAL.md;")
    print(f"then: python scripts/modules.py check {module_id} && python scripts/modules.py docs")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    n = sub.add_parser("new", help="scaffold a module")
    n.add_argument("id")
    n.add_argument("--owner", required=True, help="GitHub user id of the owner")
    n.add_argument("--name", required=True)
    n.add_argument("--provides", default="page,api", help="comma list of page, activity-card, api, events")
    c = sub.add_parser("check", help="validate modules")
    c.add_argument("ids", nargs="*")
    sub.add_parser("docs", help="regenerate modules/INDEX.md and docs/MODULES_MANUAL.md")
    sub.add_parser("list", help="list modules")
    args = ap.parse_args()
    if args.cmd == "new":
        return cmd_new(args.id, args.owner, args.name, [p.strip() for p in args.provides.split(",") if p.strip()])
    if args.cmd == "check":
        return cmd_check(args.ids)
    if args.cmd == "docs":
        return cmd_docs()
    for i in discover():
        print(
            f"{i.id:24} {i.manifest.get('version', '?'):8} @{i.manifest.get('owner', {}).get('github', '?'):20} {i.status}"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
